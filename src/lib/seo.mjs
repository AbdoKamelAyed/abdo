// Structured data (JSON-LD), sitemap.xml and robots.txt.
//
// Everything emitted here mirrors what is visible on the page. Organization schema is never used
// because there is no organization - ABDO is a person.

import { esc } from '../core/text.mjs';

const CONTEXT = 'https://schema.org';

const dateOnly = (iso) => iso.slice(0, 10);

function personRef(model, L) {
  if (!L.profile) return undefined;
  return { '@type': 'Person', name: L.profile.name, url: model.absolute(L.pageUrl.about) };
}

export function websiteLd(model, L) {
  return {
    '@context': CONTEXT,
    '@type': 'WebSite',
    name: L.siteName,
    description: L.description,
    url: model.absolute(L.homeUrl),
    inLanguage: L.lang,
    // Tells search engines the site has its own search, and how to open it with a query (the search page itself is noindex).
    ...(L.searchEnabled ? {
      potentialAction: {
        '@type': 'SearchAction',
        target: { '@type': 'EntryPoint', urlTemplate: `${model.absolute(L.pageUrl.search)}?q={search_term_string}` },
        'query-input': 'required name=search_term_string',
      },
    } : {}),
  };
}

export function personPageLd(model, L, imageUrl) {
  const profile = L.profile;
  const sameAs = profile.links.filter((l) => l.kind !== 'email').map((l) => l.url);
  return {
    '@context': CONTEXT,
    '@type': 'ProfilePage',
    url: model.absolute(L.pageUrl.about),
    inLanguage: L.lang,
    mainEntity: {
      '@type': 'Person',
      name: profile.name,
      description: profile.headline,
      ...(imageUrl ? { image: imageUrl } : {}),
      ...(sameAs.length ? { sameAs } : {}),
    },
  };
}

export function articleLd(model, L, a) {
  return {
    '@context': CONTEXT,
    '@type': 'BlogPosting',
    headline: a.title,
    description: a.excerpt,
    inLanguage: L.lang,
    url: model.absolute(a.url),
    mainEntityOfPage: model.absolute(a.url),
    datePublished: a.publishedAt,
    dateModified: a.updatedAt,
    author: personRef(model, L),
    ...(a.cover?.isRaster ? { image: a.cover.absoluteUrl } : {}),
    ...(a.primaryTopic ? { articleSection: a.primaryTopic.name } : {}),
    ...(a.tags.length ? { keywords: a.tags.map((t) => t.name).join(', ') } : {}),
  };
}

export function projectLd(model, L, p) {
  return {
    '@context': CONTEXT,
    '@type': 'CreativeWork',
    name: p.title,
    description: p.summary,
    inLanguage: L.lang,
    url: model.absolute(p.url),
    datePublished: p.publishedAt,
    ...(p.startDate ? { dateCreated: p.startDate } : {}),
    author: personRef(model, L),
    ...(p.cover?.isRaster ? { image: p.cover.absoluteUrl } : {}),
    ...(p.tags.length ? { keywords: p.tags.map((t) => t.name).join(', ') } : {}),
  };
}

export function breadcrumbLd(model, trail) {
  return {
    '@context': CONTEXT,
    '@type': 'BreadcrumbList',
    itemListElement: trail.map((crumb, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: crumb.label,
      item: model.absolute(crumb.url),
    })),
  };
}

export function collectionLd(model, L, { name, description, url, items }) {
  return {
    '@context': CONTEXT,
    '@type': 'CollectionPage',
    name,
    ...(description ? { description } : {}),
    url: model.absolute(url),
    inLanguage: L.lang,
    mainEntity: {
      '@type': 'ItemList',
      itemListElement: items.map((item, i) => ({
        '@type': 'ListItem',
        position: i + 1,
        name: item.title ?? item.name,
        url: model.absolute(item.url),
      })),
    },
  };
}

/** @param {{ url: string, lastmod?: string, alternates: Record<string,string> }[]} entries */
export function sitemapXml(model, entries) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
  ];
  for (const entry of entries) {
    lines.push('  <url>');
    lines.push(`    <loc>${esc(model.absolute(entry.url))}</loc>`);
    if (entry.lastmod) lines.push(`    <lastmod>${dateOnly(entry.lastmod)}</lastmod>`);
    const langs = Object.keys(entry.alternates);
    if (langs.length > 1) {
      for (const code of langs) {
        lines.push(`    <xhtml:link rel="alternate" hreflang="${esc(code)}" href="${esc(model.absolute(entry.alternates[code]))}"/>`);
      }
      const fallback = entry.alternates[model.defaultLang];
      if (fallback) lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${esc(model.absolute(fallback))}"/>`);
    }
    lines.push('  </url>');
  }
  lines.push('</urlset>', '');
  return lines.join('\n');
}

export function robotsTxt(model, { admin = false } = {}) {
  return [
    '# Generated by the ABDO build. Per-crawler controls arrive with the Agentic Web phase.',
    'User-agent: *',
    'Allow: /',
    ...(admin ? [`Disallow: ${model.basePath}/admin/`] : []),
    '',
    `Sitemap: ${model.absolute(`${model.basePath}/sitemap.xml`)}`,
    '',
  ].join('\n');
}
