import { layoutCss } from '../core/layout.mjs';

// Generates theme.css (design tokens + per-language typography) and glass.css (Glass Mode).
//
// Both files are pure functions of content/config/*.json. They are separate on purpose:
// Glass Mode never reads or writes colour-theme settings except the page background it blends with.

const MODE_VARS = {
  bg: '--bg', surface: '--surface', text: '--text', muted: '--muted', border: '--border',
  primary: '--primary', onPrimary: '--on-primary', secondary: '--secondary', accent: '--accent',
};

export const HERO_MIN_OPACITY = 85;

const SHADOWS = {
  none: 'none',
  soft: '0 8px 30px rgb(0 0 0 / 0.07)',
  medium: '0 12px 40px rgb(0 0 0 / 0.14)',
  strong: '0 18px 56px rgb(0 0 0 / 0.26)',
};

/** The preset, then the owner's site-wide changes, then (when `lang` is given) that language's own colours. */
export function resolvePreset(design, presets, lang = null) {
  const preset = presets.find((p) => p.key === design.preset);
  if (!preset) throw new Error(`Unknown design preset "${design.preset}"`);
  const o = design.overrides ?? {};
  const l = (lang && design.languageOverrides?.[lang]) || {};
  return {
    light: { ...preset.tokens.light, ...(o.light ?? {}), ...(l.light ?? {}) },
    dark: { ...preset.tokens.dark, ...(o.dark ?? {}), ...(l.dark ?? {}) },
    shared: { ...preset.tokens.shared, ...(o.shared ?? {}) },
  };
}

const modeBlock = (tokens = {}) => Object.entries(MODE_VARS).filter(([key]) => tokens[key] !== undefined).map(([key, name]) => `${name}:${tokens[key]};`).join('');

/** Emit the same declarations for light, `prefers-color-scheme: dark` and an explicit dark choice. */
function schemeRules(light, dark, selector = ':root') {
  return [
    `${selector}{${light}color-scheme:light;}`,
    `@media (prefers-color-scheme: dark){${selector}:not([data-theme="light"]){${dark}color-scheme:dark;}}`,
    `${selector}[data-theme="dark"]{${dark}color-scheme:dark;}`,
    `${selector}[data-theme="light"]{${light}color-scheme:light;}`,
  ].join('\n');
}

export function generateThemeCss(design, presets, languages) {
  const tokens = resolvePreset(design, presets);
  const shared = tokens.shared;
  const sharedCss = [
    `--radius:${shared.radius};`,
    `--radius-lg:${shared.radiusLarge};`,
    `--section-space:${shared.sectionSpacing};`,
    `--gutter:${shared.gutter};`,
    shared.cardShadow && shared.cardShadow !== 'none' ? `--card-shadow:${SHADOWS[shared.cardShadow]};` : '',
  ].join('');
  const backdropLight = shared.backdropLight ? `--backdrop:${shared.backdropLight};` : '--backdrop:none;';
  const backdropDark = shared.backdropDark ? `--backdrop:${shared.backdropDark};` : '--backdrop:none;';

  const out = [
    `/* Generated by the ABDO build from content/config/design.json (preset: ${design.preset}). Do not edit. */`,
    `:root{${sharedCss}}`,
    schemeRules(modeBlock(tokens.light) + backdropLight, modeBlock(tokens.dark) + backdropDark),
  ];

  const motion = { none: '0ms', subtle: '160ms', full: '280ms' }[design.animation];
  out.push(`:root{--dur:${motion};}`);
  out.push('@media (prefers-reduced-motion: reduce){:root{--dur:0ms;}}');

  for (const language of languages) {
    const ty = language.typography;
    out.push(
      `html[lang="${language.code}"]{`
      + `--font-heading:${ty.fonts.heading};--font-body:${ty.fonts.body};--font-mono:${ty.fonts.mono ?? 'ui-monospace, monospace'};`
      + `--fs-base:${ty.baseSize};--lh-body:${ty.lineHeight};--lh-heading:${ty.headingLineHeight};`
      + `--ls-body:${ty.letterSpacing};--heading-weight:${ty.headingWeight};`
      + `--content-width:${language.layout.contentWidth};--measure:${language.layout.measure};}`,
    );
    // Colours that belong to this language only: just the keys the owner changed, merged over the site-wide ones.
    const own = design.languageOverrides?.[language.code];
    if (own && (Object.keys(own.light ?? {}).length || Object.keys(own.dark ?? {}).length)) {
      out.push(schemeRules(modeBlock(own.light), modeBlock(own.dark), `html[lang="${language.code}"]`));
    }
    const shape = layoutCss(language);
    if (shape) out.push(shape);
  }
  return `${out.join('\n')}\n`;
}

// Glass Mode targets. `edge` says which border a bar-shaped element shows (the one facing the page).
const ELEMENTS = {
  header: { selector: '.site-header', edge: 'border-block-end' },
  footer: { selector: '.site-footer', edge: 'border-block-start' },
  menu: { selector: '.site-nav.is-open, .lang-switch, .theme-toggle', edge: 'border' },
  cards: { selector: '.card, .callout, .facts', edge: 'border' },
  hero: { selector: '.hero__panel', edge: 'border', opacityVar: '--glass-opacity-hero' },
};

export function generateGlassCss(design, presets) {
  const glass = design.glass;
  const tokens = resolvePreset(design, presets);
  const header = '/* Generated by the ABDO build from content/config/design.json (glass). Do not edit. */\n';
  if (!glass.enabled) return `${header}/* Glass Mode is turned off. */\n`;

  const vars = (mode, modeTokens) => [
    `--glass-blur:${mode.blur}px;`,
    `--glass-opacity:${mode.opacity}%;`,
    // Hero panels sit on photographs, so they never go below 85% opacity: text must stay readable.
    `--glass-opacity-hero:${Math.max(mode.opacity, HERO_MIN_OPACITY)}%;`,
    `--glass-surface:${mode.surface ?? modeTokens.bg};`,
    `--glass-border:${mode.border ? '1px solid color-mix(in srgb, var(--text) 14%, transparent)' : '1px solid transparent'};`,
    `--glass-shadow:${SHADOWS[mode.shadow]};`,
  ].join('');

  const active = Object.entries(glass.elements).filter(([, on]) => on).map(([name]) => ELEMENTS[name]);
  const out = [header, schemeRules(vars(glass.light, tokens.light), vars(glass.dark, tokens.dark))];
  if (active.length) {
    out.push(
      '/* Applied only where the browser can blur what is behind an element; everywhere else the',
      '   solid surface colours from base.css remain, so nothing becomes unreadable. */',
      '@supports ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px))) and (background: color-mix(in srgb, red 50%, transparent)){',
    );
    for (const { selector, edge, opacityVar = '--glass-opacity' } of active) {
      out.push(
        `${selector}{`,
        `  background:color-mix(in srgb, var(--glass-surface) var(${opacityVar}), transparent);`,
        '  -webkit-backdrop-filter:blur(var(--glass-blur)) saturate(140%);',
        '  backdrop-filter:blur(var(--glass-blur)) saturate(140%);',
        `  ${edge}:var(--glass-border);`,
        '  box-shadow:var(--glass-shadow);',
        '}',
      );
    }
    out.push('}');
  }
  return `${out.join('\n')}\n`;
}

/** Google Fonts stylesheet URL for one language, or null when it only uses system fonts. */
export function googleFontsUrl(language) {
  const families = language.typography.googleFonts;
  if (!families.length) return null;
  return `https://fonts.googleapis.com/css2?${families.join('&')}&display=swap`;
}
